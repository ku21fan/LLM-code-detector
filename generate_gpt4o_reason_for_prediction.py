import argparse
import asyncio
import json
import os
from collections import defaultdict

import base64
import aiohttp
import tqdm

import time

NUM_SECONDS_TO_SLEEP = 0.5


prompt_student_reason_for_prediction = """The following code snippet was written by a student in response to an assignment from an introductory Python programming course.

Here are some common characteristics of student-written code:
1. Students often use explicit `for` loops and manual indexing (`range(len(...))`) rather than more concise Python constructs.
2. The logic is sometimes redundant or overly complicated, with repeated or verbose conditional checks.
3. Data structures are used inefficiently, such as manually counting instead of using tools like `collections.Counter`.
4. Variable names tend to be unclear or inconsistent (e.g., `x`, `tmp`, `ans`), and code style varies significantly between snippets.

Based on these characteristics, and considering the assignment, please explain the reasons for the prediction — why you would consider this code to have been written by a student.  
Your reasoning should refer to specific elements in the code that align with the above characteristics and the task.  
Please summarize your reasoning in no more than 5 lines.

Assignment:
{problem}

Code snippet:
{code}"""


prompt_llm_reason_for_prediction = """The following code snippet was generated by a large language model (LLM) in response to an assignment from an introductory Python programming course.

Here are some common characteristics of LLM-generated code:
1. Each snippet solves the assigned task with complete functionality, but similar logic structures often appear with only minor variations.
2. Variable names are consistently descriptive and context-appropriate, often using synonyms to introduce subtle variety.
3. The code tends to include explicit handling of edge cases and invalid inputs, showing a bias toward defensive programming.
4. Simple loops, sorting, and accumulators are commonly used to solve problems in a direct and readable way, well-suited for introductory tasks.

Based on these characteristics, and considering the assignment, please explain the reasons for the prediction — why you would consider this code to have been generated by an LLM.  
Your reasoning should refer to specific patterns or tendencies in the code that align with the above characteristics and the task.  
Please summarize your reasoning in no more than 5 lines.

Assignment:
{problem}

Code snippet:
{code}"""


async def get_response(session, content: str, max_tokens: int):
    url = "https://api.openai.com/v1/chat/completions"
    headers = {
        "Authorization": f"Bearer {os.getenv('OPENAI_API_KEY') }",
        "Content-Type": "application/json",
    }
    payload = {
        "model": "gpt-4o-2024-11-20",
        "messages": [{"role": "user", "content": content},],
        "temperature": 1.0,  # for diversity
        "max_tokens": max_tokens,
    }

    while True:
        try:
            async with session.post(url, headers=headers, json=payload) as resp:
                if resp.status == 429:
                    await asyncio.sleep(NUM_SECONDS_TO_SLEEP)
                    continue
                resp.raise_for_status()
                data = await resp.json()
                return data["choices"][0]["message"]["content"]
        except Exception as e:
            print(e)


async def main(args):
    async with aiohttp.ClientSession() as session:

        input_path = open(os.path.expanduser(args.input_path))

        if os.path.isfile(os.path.expanduser(args.output_path)):
            cur_responses = [
                json.loads(line) for line in open(os.path.expanduser(args.output_path))
            ]
        else:
            cur_responses = []

        output_file = open(f"{args.output_path}", "w")

        tasks = []
        cur_js_list = []
        for idx, jsonline in tqdm.tqdm(enumerate(input_path)):
            line = json.loads(jsonline)
            try:
                data_id = line["id"]
                problem_name = line["problem_name"]
                problem = line["problem"]
                code = line["code"]
                label = line["label"]
            except:
                assert idx, jsonline

            cur_js = {
                "id": data_id,
                "problem_name": problem_name,
                "problem": problem,
                "code": code,
                "label": label,
            }

            if label == 1:
                prompt = prompt_llm_reason_for_prediction
            else:
                prompt = prompt_student_reason_for_prediction

            content = prompt.format(problem=problem, code=code)

            if idx >= len(cur_responses):
                task = asyncio.create_task(
                    get_response(session, content, args.max_tokens)
                )
                tasks.append(task)
                cur_js_list.append(cur_js)
            else:
                print(f"Skipping {idx} as we already have it.")

        # Wait for all tasks to complete
        results = await asyncio.gather(*tasks)

        # Process results and write to file as before
        for result, cur_js in zip(results, cur_js_list):
            # Assuming `cur_js` is prepared as before:
            cur_js["reason_for_prediction"] = result
            output_file.write(json.dumps(cur_js, ensure_ascii=False) + "\n")
            output_file.flush()

        output_file.close()


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="ChatGPT-based QA evaluation.")
    parser.add_argument("-i", "--input_path")
    parser.add_argument("-o", "--output_path")
    parser.add_argument(
        "--max-tokens",
        type=int,
        default=1024,
        help="maximum number of tokens produced in the output",
    )
    args = parser.parse_args()

    start_time = time.time()
    asyncio.run(main(args))

    end_time = time.time()
    elapsed_time = end_time - start_time
    print(f"Elapsed time: {elapsed_time:.0f} seconds")
